<?php

declare(strict_types=1);

namespace App\Actions\Domains;

use App\Actions\Audit\RecordAuditEvent;
use App\Data\Audit\AuditActor;
use App\Data\Audit\AuditEntryData;
use App\Enums\AuditAction;
use App\Enums\DomainKind;
use App\Exceptions\DomainRuleViolation;
use App\Models\Domain;
use App\Models\InstanceSettings;
use App\Models\ServiceInstance;
use App\Support\Hostname;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;

/**
 * Adds a custom domain to a service instance (docs/05 §5). It applies
 * immediately (ApplyDomainRoutes): the edges start routing it without a
 * deploy. Certificates come from on-demand TLS approved by the edge daemon.
 */
final readonly class AddDomain
{
    public function __construct(
        private RecordAuditEvent $audit,
        private ApplyDomainRoutes $routes,
    ) {}

    public function handle(ServiceInstance $instance, string $hostname, AuditActor $actor, ?string $redirectTo = null): Domain
    {
        $hostname = Hostname::normalize($hostname);

        if (! Hostname::isValid($hostname) || Hostname::isLocal($hostname)) {
            throw DomainRuleViolation::on('hostname', 'Enter a valid domain name such as shop.example.com (no underscores, labels up to 63 characters).');
        }

        // Names under the platform domain are launchroom's generated
        // addresses: claiming one would squat another project's (review L9).
        $appsDomain = InstanceSettings::current()->apps_domain;

        if (is_string($appsDomain) && $appsDomain !== '' && ($hostname === strtolower($appsDomain) || str_ends_with($hostname, '.'.strtolower($appsDomain)))) {
            throw DomainRuleViolation::on('hostname', "Addresses under {$appsDomain} are generated by launchroom. Use a domain of your own.");
        }

        if ($redirectTo !== null && ! Hostname::isValid($redirectTo = Hostname::normalize($redirectTo))) {
            throw DomainRuleViolation::on('redirectTo', 'Enter a valid domain to redirect to.');
        }

        try {
            return DB::transaction(function () use ($instance, $hostname, $actor, $redirectTo): Domain {
                $domain = Domain::query()->create([
                    'team_id' => $instance->team_id,
                    'service_instance_id' => $instance->id,
                    'hostname' => $hostname,
                    'kind' => DomainKind::Custom,
                    'redirect_to' => $redirectTo,
                ]);

                $this->audit->handle(new AuditEntryData(
                    action: AuditAction::DomainAdded,
                    actor: $actor,
                    teamId: $instance->team_id,
                    subjectType: 'domain',
                    subjectId: $domain->public_id,
                    meta: ['hostname' => $hostname],
                ));

                $this->routes->handle($instance, $actor, "Added {$hostname}");

                return $domain;
            });
        } catch (UniqueConstraintViolationException) {
            // A hostname belongs to one service, so one team, on the install
            // (docs/05 §5); TXT ownership verification is a later addition.
            throw DomainRuleViolation::on('hostname', 'This domain is already in use.');
        }
    }
}
