<?php

declare(strict_types=1);

namespace App\Console\Vocabulary;

use App\Enums\Attributes\SharedFacts;
use App\Enums\Contracts\HasTransitionTable;
use App\Enums\StatusTone;
use BackedEnum;
use Illuminate\Support\Facades\File;
use LogicException;
use ReflectionEnum;

/**
 * Builds the TypeScript twin of the enums' presentation: every backed enum in
 * app/Enums with a `label()` (and `tone()`, `isTerminal()` of a
 * {@see HasTransitionTable}, and the methods named by {@see SharedFacts})
 * becomes one object keyed by case value, nested like the `App.Enums.*`
 * namespaces of generated.d.ts. The frontend reads words, tones and status
 * sets from it instead of keeping its own tables.
 */
final class EnumVocabulary
{
    public static function path(): string
    {
        return resource_path('js/types/vocabulary.generated.ts');
    }

    public function render(): string
    {
        $tree = [];

        foreach ($this->enums() as $class) {
            $entries = $this->entries($class);

            if ($entries === null) {
                continue;
            }

            $tree = $this->insert($tree, explode('\\', substr($class, strlen('App\\Enums\\'))), ['__enum' => $class, '__entries' => $entries]);
        }

        $this->sortTree($tree);

        return "// Generated by `make gen-types` (php artisan launchroom:vocabulary) from the\n"
            ."// label(), tone(), isTerminal() and #[SharedFacts] methods of app/Enums. Never hand-edit.\n\n"
            .'export const vocabulary = '.$this->renderNode($tree, 0)." as const;\n";
    }

    /**
     * @return list<class-string<BackedEnum>>
     */
    private function enums(): array
    {
        $classes = [];

        foreach (File::allFiles(app_path('Enums')) as $file) {
            $class = 'App\\Enums\\'.str_replace(['/', '.php'], ['\\', ''], $file->getRelativePathname());

            if (enum_exists($class) && is_subclass_of($class, BackedEnum::class)) {
                $classes[] = $class;
            }
        }

        sort($classes);

        return $classes;
    }

    /**
     * @param  class-string<BackedEnum>  $class
     * @return array<string, array<string, bool|int|string>>|null
     */
    private function entries(string $class): ?array
    {
        $reflection = new ReflectionEnum($class);
        $methods = [];

        foreach (['label', 'tone'] as $name) {
            if ($this->isFact($reflection, $name)) {
                $methods[] = $name;
            }
        }

        if ($reflection->implementsInterface(HasTransitionTable::class)) {
            $methods[] = 'isTerminal';
        }

        foreach ($reflection->getAttributes(SharedFacts::class) as $attribute) {
            foreach ($attribute->newInstance()->methods as $name) {
                if (! $this->isFact($reflection, $name)) {
                    throw new LogicException("{$class}::{$name}() must be a public, argument-free instance method.");
                }

                $methods[] = $name;
            }
        }

        if ($methods === []) {
            return null;
        }

        $entries = [];

        foreach ($class::cases() as $case) {
            $facts = [];

            foreach ($methods as $name) {
                $value = $case->{$name}();
                $facts[$name] = match (true) {
                    $value instanceof StatusTone => $value->value,
                    is_bool($value), is_int($value), is_string($value) => $value,
                    default => throw new LogicException("{$class}::{$name}() must return a bool, int, string or StatusTone."),
                };
            }

            $entries[(string) $case->value] = $facts;
        }

        return $entries;
    }

    /**
     * @param  ReflectionEnum<BackedEnum>  $reflection
     */
    private function isFact(ReflectionEnum $reflection, string $name): bool
    {
        if (! $reflection->hasMethod($name)) {
            return false;
        }

        $method = $reflection->getMethod($name);

        return $method->isPublic() && ! $method->isStatic() && $method->getNumberOfRequiredParameters() === 0;
    }

    /**
     * @param  array<string, mixed>  $tree
     * @param  list<string>  $path
     * @param  array<string, mixed>  $leaf
     * @return array<string, mixed>
     */
    private function insert(array $tree, array $path, array $leaf): array
    {
        $segment = array_shift($path);

        if ($segment === null) {
            return $leaf;
        }

        /** @var array<string, mixed> $child */
        $child = is_array($tree[$segment] ?? null) ? $tree[$segment] : [];
        $tree[$segment] = $this->insert($child, $path, $leaf);

        return $tree;
    }

    /**
     * @param  array<string, mixed>  $tree
     */
    private function sortTree(array &$tree): void
    {
        if (isset($tree['__enum'])) {
            return;
        }

        ksort($tree);

        foreach ($tree as &$child) {
            if (is_array($child)) {
                /** @var array<string, mixed> $child */
                $this->sortTree($child);
            }
        }
    }

    /**
     * @param  array<string, mixed>  $node
     */
    private function renderNode(array $node, int $depth): string
    {
        $pad = str_repeat('    ', $depth + 1);
        $close = str_repeat('    ', $depth);
        $lines = [];

        if (isset($node['__entries']) && is_array($node['__entries'])) {
            /** @var array<string, array<string, bool|int|string>> $entries */
            $entries = $node['__entries'];

            foreach ($entries as $value => $facts) {
                $parts = [];

                foreach ($facts as $key => $fact) {
                    $parts[] = $key.': '.$this->literal($fact);
                }

                $lines[] = $pad.$this->key((string) $value).': { '.implode(', ', $parts).' },';
            }
        } else {
            foreach ($node as $key => $child) {
                /** @var array<string, mixed> $child */
                $lines[] = $pad.$this->key((string) $key).': '.$this->renderNode($child, $depth + 1).',';
            }
        }

        return "{\n".implode("\n", $lines)."\n{$close}}";
    }

    private function key(string $key): string
    {
        return preg_match('/^[A-Za-z_$][A-Za-z0-9_$]*$/', $key) === 1 ? $key : $this->literal($key);
    }

    private function literal(bool|int|string $value): string
    {
        return match (true) {
            is_bool($value) => $value ? 'true' : 'false',
            is_int($value) => (string) $value,
            default => "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'",
        };
    }
}
