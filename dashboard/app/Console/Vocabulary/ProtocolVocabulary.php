<?php

declare(strict_types=1);

namespace App\Console\Vocabulary;

use App\Support\Protocol\Grammar;
use App\Support\Protocol\Limits;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;
use JsonException;
use RuntimeException;

/**
 * Renders launchroomd's protocol vocabulary (protocol/schema/v1/vocabulary.json,
 * written by schemagen from daemon/internal/state) into the dashboard's
 * generated twins: {@see Grammar} and {@see Limits} for PHP, and
 * resources/js/types/grammar.generated.ts for the frontend. Go regexes are RE2
 * and anchored with ^…$; PHP gets them with the D modifier so `$` does not
 * accept a trailing newline (RE2's `$` never does).
 */
final class ProtocolVocabulary
{
    /** @var array<string, mixed>|null */
    private ?array $vocabulary = null;

    /**
     * @return array<string, string> path relative to base_path() => contents
     */
    public function render(): array
    {
        return [
            'app/Support/Protocol/Grammar.php' => $this->grammarClass(),
            'app/Support/Protocol/Limits.php' => $this->limitsClass(),
            'resources/js/types/grammar.generated.ts' => $this->typescript(),
        ];
    }

    private function grammarClass(): string
    {
        $lines = [];

        foreach ($this->grammars() as $name => $source) {
            $lines[] = '    public const string '.$this->constant($name).' = '.$this->phpString($this->pcre($source)).';';
            $lines[] = '';
            $lines[] = '    public const string '.$this->constant($name).'_BODY = '.$this->phpString($this->body($source)).';';
            $lines[] = '';
        }

        $lines[] = '    public const array FORBIDDEN_MOUNT_TARGETS = ['.implode(', ', array_map($this->phpString(...), $this->strings('forbiddenMountTargets'))).'];';

        foreach ($this->constants() as $name => $value) {
            $lines[] = '';
            $lines[] = '    public const string '.$this->constant($name).' = '.$this->phpString($value).';';
        }

        return $this->phpClass('Grammar', 'Identifier grammars and fixed protocol strings of launchroomd. Each grammar is an anchored PCRE pattern (usable in #[Regex] and preg_match) plus its unanchored _BODY for composing (route patterns, prefixes).', $lines);
    }

    private function limitsClass(): string
    {
        $lines = [];

        foreach ($this->limits() as $name => $value) {
            $lines[] = '    public const int '.$this->constant($name).' = '.$value.';';
            $lines[] = '';
        }

        foreach ($this->intSets() as $name => $values) {
            $lines[] = '    public const array '.$this->constant($name).' = ['.implode(', ', $values).'];';
            $lines[] = '';
        }

        array_pop($lines);

        return $this->phpClass('Limits', 'Numeric limits, ports and allowed values of launchroomd\'s protocol.', $lines);
    }

    /**
     * @param  list<string>  $body
     */
    private function phpClass(string $name, string $summary, array $body): string
    {
        return "<?php\n\n"
            ."declare(strict_types=1);\n\n"
            ."namespace App\\Support\\Protocol;\n\n"
            ."/**\n"
            ." * {$summary}\n"
            ." *\n"
            ." * Generated by `make gen-types` (php artisan launchroom:protocol-vocabulary) from\n"
            ." * protocol/schema/v1/vocabulary.json. Never hand-edit.\n"
            ." */\n"
            ."final class {$name}\n"
            ."{\n"
            .implode("\n", array_map(rtrim(...), $body))."\n"
            ."}\n";
    }

    private function typescript(): string
    {
        $grammar = [];

        foreach ($this->grammars() as $name => $source) {
            $grammar[] = "    {$name}: new RegExp({$this->json($source)}),";
        }

        $limits = [];

        foreach ($this->limits() as $name => $value) {
            $limits[] = "    {$name}: {$value},";
        }

        foreach ($this->intSets() as $name => $values) {
            $limits[] = "    {$name}: [{$this->implodeJson($values)}],";
        }

        $constants = [];

        foreach ($this->constants() as $name => $value) {
            $constants[] = "    {$name}: {$this->json($value)},";
        }

        return "// Generated by `make gen-types` (php artisan launchroom:protocol-vocabulary) from\n"
            ."// protocol/schema/v1/vocabulary.json (launchroomd's grammars and limits). Never hand-edit.\n\n"
            ."export const grammar = {\n".implode("\n", $grammar)."\n} as const;\n\n"
            .'export const forbiddenMountTargets = ['.$this->implodeJson($this->strings('forbiddenMountTargets'))."] as const;\n\n"
            ."export const limits = {\n".implode("\n", $limits)."\n} as const;\n\n"
            ."export const protocolConstants = {\n".implode("\n", $constants)."\n} as const;\n";
    }

    /**
     * RE2 source (anchored with ^…$, or an unanchored fragment) → delimited PCRE.
     * RE2 matches runes; a negated class is the only construct here that can
     * match a non-ASCII character, so those grammars get PCRE's u modifier
     * (a {1,128} counts characters, not bytes, and invalid UTF-8 never matches).
     */
    private function pcre(string $source): string
    {
        $body = $this->body($source);

        return '/^'.$this->escapeDelimiter($body).'$/D'.(str_contains($body, '[^') ? 'u' : '');
    }

    private function body(string $source): string
    {
        $body = $source;

        if (str_starts_with($body, '^') && str_ends_with($body, '$') && ! str_ends_with($body, '\\$')) {
            $body = substr($body, 1, -1);
        }

        return str_contains($body, '|') && ! $this->isGroup($body) ? '(?:'.$body.')' : $body;
    }

    private function isGroup(string $body): bool
    {
        if (! str_starts_with($body, '(') || ! str_ends_with($body, ')')) {
            return false;
        }

        $depth = 0;
        $length = strlen($body);

        for ($i = 0; $i < $length; $i++) {
            if ($body[$i] === '\\') {
                $i++;

                continue;
            }

            $depth += match ($body[$i]) {
                '(' => 1,
                ')' => -1,
                default => 0,
            };

            if ($depth === 0 && $i < $length - 1) {
                return false;
            }
        }

        return true;
    }

    private function escapeDelimiter(string $pattern): string
    {
        $out = '';
        $length = strlen($pattern);

        for ($i = 0; $i < $length; $i++) {
            if ($pattern[$i] === '\\') {
                $out .= $pattern[$i].($pattern[$i + 1] ?? '');
                $i++;

                continue;
            }

            $out .= $pattern[$i] === '/' ? '\\/' : $pattern[$i];
        }

        return $out;
    }

    private function constant(string $name): string
    {
        return strtoupper(Str::snake($name));
    }

    private function phpString(string $value): string
    {
        return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
    }

    private function json(string $value): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }

    /**
     * @param  list<int|string>  $values
     */
    private function implodeJson(array $values): string
    {
        return implode(', ', array_map(fn (int|string $v): string => is_int($v) ? (string) $v : $this->json($v), $values));
    }

    /**
     * @return array<string, string>
     */
    private function grammars(): array
    {
        return array_map(static fn (int|string $v): string => is_string($v) ? $v : throw new RuntimeException('vocabulary.json: grammars'), $this->sortedMap('grammars'));
    }

    /**
     * @return array<string, string>
     */
    private function constants(): array
    {
        return array_map(static fn (int|string $v): string => is_string($v) ? $v : throw new RuntimeException('vocabulary.json: constants'), $this->sortedMap('constants'));
    }

    /**
     * @return array<string, int>
     */
    private function limits(): array
    {
        return array_map(static fn (int|string $v): int => is_int($v) ? $v : throw new RuntimeException('vocabulary.json: limits'), $this->sortedMap('limits'));
    }

    /**
     * @return array<string, list<int>>
     */
    private function intSets(): array
    {
        $sets = $this->vocabulary()['intSets'] ?? null;

        if (! is_array($sets)) {
            throw new RuntimeException('vocabulary.json: intSets missing');
        }

        $out = [];

        foreach ($sets as $name => $values) {
            if (! is_string($name) || ! is_array($values) || ! array_is_list($values)) {
                throw new RuntimeException("vocabulary.json: intSets.{$name} is not a list");
            }

            $out[$name] = array_map(static fn (mixed $v): int => is_int($v) ? $v : throw new RuntimeException("vocabulary.json: intSets.{$name}"), $values);
        }

        ksort($out);

        return $out;
    }

    /**
     * @return list<string>
     */
    private function strings(string $key): array
    {
        $values = $this->vocabulary()[$key] ?? null;

        if (! is_array($values) || ! array_is_list($values)) {
            throw new RuntimeException("vocabulary.json: {$key} is not a list");
        }

        return array_map(static fn (mixed $v): string => is_string($v) ? $v : throw new RuntimeException("vocabulary.json: {$key}"), $values);
    }

    /**
     * @return array<string, int|string>
     */
    private function sortedMap(string $key): array
    {
        $map = $this->vocabulary()[$key] ?? null;

        if (! is_array($map)) {
            throw new RuntimeException("vocabulary.json: {$key} missing");
        }

        $out = [];

        foreach ($map as $name => $value) {
            if (! is_string($name) || (! is_int($value) && ! is_string($value))) {
                throw new RuntimeException("vocabulary.json: {$key} has an invalid entry");
            }

            $out[$name] = $value;
        }

        ksort($out);

        return $out;
    }

    /**
     * @return array<string, mixed>
     */
    private function vocabulary(): array
    {
        if ($this->vocabulary !== null) {
            return $this->vocabulary;
        }

        $path = rtrim(config()->string('launchroom.protocol.schema_path'), '/').'/vocabulary.json';

        try {
            $decoded = json_decode(File::get($path), true, 16, JSON_THROW_ON_ERROR);
        } catch (JsonException $e) {
            throw new RuntimeException("{$path} is not valid JSON", $e->getCode(), previous: $e);
        }

        if (! is_array($decoded)) {
            throw new RuntimeException("{$path} is not an object");
        }

        /** @var array<string, mixed> $decoded */
        return $this->vocabulary = $decoded;
    }
}
