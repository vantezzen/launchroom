"""Dotted world map for ServerMap (docs/design/direction.md §5.10).

Samples Natural Earth 110 m land polygons (public domain,
https://www.naturalearthdata.com) on a regular lon/lat grid and writes the
land dots as one compact SVG path ("M x y h0" per dot, drawn with round line
caps) into resources/js/components/map/land-dots.generated.ts. The output is
committed; rerun only to change the grid:

  make world-map
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

import numpy as np

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson"
STEP = 2.0  # degrees between dots
LAT_MAX, LAT_MIN = 76.0, -56.0  # crop the poles (Antarctica, the Arctic ice)
LON_MIN, LON_MAX = -170.0, 190.0  # shift so the Bering strait splits Asia and America cleanly
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "/out/land-dots.generated.ts")


def rings(geojson: dict) -> list[np.ndarray]:
    out: list[np.ndarray] = []
    for feature in geojson["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            for ring in poly:
                out.append(np.asarray(ring, dtype=np.float64))
    return out


def inside(lon: np.ndarray, lat: np.ndarray, polygon_rings: list[np.ndarray]) -> np.ndarray:
    """Even-odd ray casting over all rings (holes cancel out)."""
    hit = np.zeros(lon.shape, dtype=bool)
    for ring in polygon_rings:
        x1, y1 = ring[:-1, 0], ring[:-1, 1]
        x2, y2 = ring[1:, 0], ring[1:, 1]
        for a, b, c, d in zip(x1, y1, x2, y2):
            if b == d:
                continue
            crosses = (lat > min(b, d)) & (lat <= max(b, d))
            xi = a + (lat - b) * (c - a) / (d - b)
            hit ^= crosses & (lon < xi)
    return hit


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:  # noqa: S310 (pinned https URL)
        data = json.load(response)
    polygon_rings = rings(data)

    lons = np.arange(LON_MIN + STEP / 2, LON_MAX, STEP)
    lats = np.arange(LAT_MAX - STEP / 2, LAT_MIN, -STEP)
    grid_lon, grid_lat = np.meshgrid(lons, lats)
    wrapped = np.where(grid_lon > 180, grid_lon - 360, grid_lon)
    land = inside(wrapped.ravel(), grid_lat.ravel(), polygon_rings).reshape(grid_lon.shape)

    cols, rows = len(lons), len(lats)
    parts = []
    for r in range(rows):
        for c in range(cols):
            if land[r, c]:
                parts.append(f"M{c} {r}h0")
    path = "".join(parts)

    OUT.write_text(
        "// Generated by dashboard/scripts/world-map/build.py from Natural Earth 110 m land\n"
        "// (public domain). Do not edit; rerun `make world-map`.\n"
        "// One dot per grid cell: x = column, y = row (dot centres), drawn with round caps.\n"
        "export const LAND_GRID = {\n"
        f"    step: {STEP},\n"
        f"    latMax: {LAT_MAX},\n"
        f"    lonMin: {LON_MIN},\n"
        f"    cols: {cols},\n"
        f"    rows: {rows},\n"
        "} as const;\n"
        f"export const LAND_DOT_COUNT = {len(parts)};\n"
        f"export const LAND_DOTS_PATH =\n    '{path}';\n"
    )
    print(f"{len(parts)} land dots on a {cols}x{rows} grid -> {OUT}")


if __name__ == "__main__":
    main()
