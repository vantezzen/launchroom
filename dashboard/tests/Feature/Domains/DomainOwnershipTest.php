<?php

declare(strict_types=1);

use App\Actions\Domains\AddDomain;
use App\Data\Audit\AuditActor;
use App\Exceptions\DomainRuleViolation;
use App\Models\Domain;
use App\Models\InstanceSettings;
use App\Models\ServiceInstance;
use App\Models\Team;
use App\Support\Hostname;
use Tests\Support\Projects;

/**
 * L9 (2026-10 security review): custom domains are real domain names, owned
 * by one team, and never launchroom's generated addresses.
 */
beforeEach(fn () => Projects::useTestKek());

function webInstance(?Team $team = null): ServiceInstance
{
    $project = Projects::create($team ?? Team::factory()->create(), 'shop-'.bin2hex(random_bytes(3)));
    $web = Projects::image($project);

    return ServiceInstance::query()->where('service_id', $web->id)->where('environment_id', $project->production()->sole()->id)->sole();
}

test('IP literals and numeric TLDs are not domains', function (string $hostname): void {
    expect(Hostname::isValid($hostname))->toBeFalse()
        ->and(fn () => resolve(AddDomain::class)->handle(webInstance(), $hostname, AuditActor::system()))
        ->toThrow(DomainRuleViolation::class, 'valid domain');
})->with(['10.0.0.5', '127.0.0.1', '169.254.169.254', '1.2.3.4.', 'example.123']);

test('a hostname belongs to one team: another team cannot claim it', function (): void {
    resolve(AddDomain::class)->handle(webInstance(), 'shop.example.com', AuditActor::system());

    expect(fn () => resolve(AddDomain::class)->handle(webInstance(), 'SHOP.example.com.', AuditActor::system()))
        ->toThrow(DomainRuleViolation::class, 'already in use')
        ->and(Domain::query()->where('hostname', 'shop.example.com')->count())->toBe(1);
});

test('generated addresses under the platform domain cannot be claimed as custom domains', function (): void {
    InstanceSettings::current()->forceFill(['apps_domain' => 'apps.example.com'])->save();

    expect(fn () => resolve(AddDomain::class)->handle(webInstance(), 'web-production.other-project.apps.example.com', AuditActor::system()))
        ->toThrow(DomainRuleViolation::class, 'generated by launchroom')
        ->and(fn () => resolve(AddDomain::class)->handle(webInstance(), 'apps.example.com', AuditActor::system()))
        ->toThrow(DomainRuleViolation::class, 'generated by launchroom');

    expect(resolve(AddDomain::class)->handle(webInstance(), 'shop.example.com', AuditActor::system())->hostname)->toBe('shop.example.com');
});
