<?php

declare(strict_types=1);

use App\Services\Daemon\Exceptions\InvalidRequestSignature;
use App\Services\Daemon\HttpMessageSignature;
use App\Services\Daemon\SignedRequest;
use App\Support\Crypto\PublicKeyFormat;
use Tests\Support\ProtocolSchemas;

/*
| Shared test vectors from protocol/fixtures/signing (generated by the Go
| daemon). The PHP implementation must reproduce them byte for byte.
*/

/**
 * @return array<string, array{0: array<string, mixed>}> dataset: name => [vector]
 */
function requestVectors(): array
{
    $vectors = [];

    foreach (['request-get-state', 'request-post-lease', 'request-enroll'] as $name) {
        $vectors[$name] = [json_decode((string) file_get_contents(ProtocolSchemas::root()."/fixtures/signing/{$name}.json"), true, flags: JSON_THROW_ON_ERROR)];
    }

    return $vectors;
}

/**
 * @param  array<string, mixed>  $vector
 * @param  array<string, string>  $override
 */
function vectorRequest(array $vector, array $override = []): SignedRequest
{
    $url = parse_url($vector['request']['url']);
    $target = ($url['path'] ?? '/').(isset($url['query']) ? '?'.$url['query'] : '');

    return new SignedRequest(
        $override['method'] ?? $vector['request']['method'],
        $override['target'] ?? $target,
        [
            'signature-input' => [$vector['expected']['signatureInput']],
            'signature' => [$vector['expected']['signature']],
            'content-digest' => [$vector['expected']['contentDigest']],
            'date' => [$vector['expected']['date']],
            'x-lr-nonce' => [$override['nonce'] ?? $vector['expected']['nonce']],
        ],
        $override['body'] ?? $vector['request']['body'],
    );
}

/**
 * @param  array<string, mixed>  $vector
 */
function verifyVector(array $vector, SignedRequest $request, int $at): void
{
    $parsed = HttpMessageSignature::parse($request, $at, $vector['maxSkewSeconds']);
    expect($parsed->keyId)->toBe($vector['keyId']);
    HttpMessageSignature::verify($parsed, (string) PublicKeyFormat::parseEd25519($vector['publicKey']));
}

test('reproduces the signature base and signature of every vector', function (array $vector): void {
    $seed = base64_decode($vector['privateKeySeed'], true);
    $secret = sodium_crypto_sign_secretkey(sodium_crypto_sign_seed_keypair((string) $seed));
    $url = parse_url($vector['request']['url']);
    $target = ($url['path'] ?? '/').(isset($url['query']) ? '?'.$url['query'] : '');

    $headers = HttpMessageSignature::sign(
        $vector['request']['method'],
        $target,
        $vector['request']['body'],
        $vector['keyId'],
        $secret,
        $vector['created'],
        (string) base64_decode($vector['nonceBytes'], true),
    );

    expect($headers['Content-Digest'])->toBe($vector['expected']['contentDigest'])
        ->and($headers['Date'])->toBe($vector['expected']['date'])
        ->and($headers['X-LR-Nonce'])->toBe($vector['expected']['nonce'])
        ->and($headers['Signature-Input'])->toBe($vector['expected']['signatureInput'])
        ->and($headers['Signature'])->toBe($vector['expected']['signature'])
        ->and(HttpMessageSignature::signatureBase(vectorRequest($vector), substr($vector['expected']['signatureInput'], 5)))
        ->toBe($vector['expected']['signatureBase']);
})->with(requestVectors());

test('accepts every vector at verifyAt', function (array $vector): void {
    expect(fn () => verifyVector($vector, vectorRequest($vector), $vector['verifyAt']))
        ->not->toThrow(InvalidRequestSignature::class);
})->with(requestVectors());

test('rejects tampered vectors', function (array $vector, string $tamper): void {
    $override = match ($tamper) {
        'body' => ['body' => $vector['request']['body'].' '],
        'method' => ['method' => $vector['request']['method'] === 'GET' ? 'POST' : 'GET'],
        'query' => ['target' => parse_url($vector['request']['url'], PHP_URL_PATH).'?have=1'],
        'nonce' => ['nonce' => 'AAAAAAAAAAAAAAAAAAAAAA'],
        default => [],
    };

    $at = $tamper === 'late' ? $vector['verifyAt'] + 61 : $vector['verifyAt'];

    verifyVector($vector, vectorRequest($vector, $override), $at);
})->with(requestVectors())->with(['body', 'method', 'query', 'nonce', 'late'])->throws(InvalidRequestSignature::class);

test('rejects repeated headers and malformed parameters', function (array $vector, string $case): void {
    $request = vectorRequest($vector);
    $headers = $request->headers;

    match ($case) {
        'duplicate-date' => $headers['date'][] = $headers['date'][0],
        'missing-nonce' => $headers['x-lr-nonce'] = [],
        'other-tag' => $headers['signature-input'] = [str_replace('launchroomd-v1', 'other', $headers['signature-input'][0])],
        'reordered' => $headers['signature-input'] = [str_replace('"@method" "@path"', '"@path" "@method"', $headers['signature-input'][0])],
        'lowercase-date' => $headers['date'] = [strtolower($headers['date'][0])],
        default => null,
    };

    verifyVector($vector, new SignedRequest($request->method, $request->requestTarget, $headers, $request->body), $vector['verifyAt']);
})->with(['get-state' => [requestVectors()['request-get-state'][0]]])->with(['duplicate-date', 'missing-nonce', 'other-tag', 'reordered', 'lowercase-date'])
    ->throws(InvalidRequestSignature::class);
