// html renders the page; status is the code shown (a number or a placeholder).
func (p errorPage) html(status string) string {
	var b strings.Builder
	b.WriteString(`<!doctype html><html lang="en"><head><meta charset="utf-8">`)
	b.WriteString(`<meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex">`)
	if p.refresh {
		b.WriteString(`<meta http-equiv="refresh" content="10">`)
	}
	b.WriteString(`<title>` + html.EscapeString(p.title) + `</title><style>` + pageCSS + `</style></head><body><main>`)
	b.WriteString(`<header>` + pageMark + `launchroom</header>`)
	b.WriteString(`<p class="c">Error ` + status + `</p>`)
	b.WriteString(`<h1>` + html.EscapeString(p.title) + `</h1><p>` + html.EscapeString(p.text) + `</p>`)
	if p.host {
		b.WriteString(`<div class="h">{http.request.host}</div>`)
	}
	if p.reference {
		b.WriteString(`<div class="h">Reference ` + wafReferencePlaceholder + `</div>`)
	}
	b.WriteString(`</main></body></html>`)
	return b.String()
}

// errorRoutes are the HTTPS server's errors routes: a request the web
// firewall refused answers with the blocked page (403, firewalled hosts
// only); a failed reverse_proxy
// (502, 503, 504) answers with a page and keeps the error's status. The
// dashboard's route says launchroom is restarting, app routes that the app
// is not answering, anything else (e.g. the reachability check) a page
// without the host. Other errors keep Caddy's empty answer.
func (o Options) errorRoutes(routes []Route) []any {
	var dashboard, apps, firewalled []string
	for _, r := range WafRoutes(routes, o) {
		for _, h := range r.Spec.Hosts {
			firewalled = append(firewalled, string(h))
		}
	}
	var out []any
	if len(firewalled) > 0 {
		out = append(out, wafErrorRoute(firewalled))
	}
	for _, r := range routes {
		for _, h := range r.Spec.Hosts {
			if o.localOnly(r) {
				dashboard = append(dashboard, string(h))
			} else {
				apps = append(apps, string(h))
			}
		}
	}
	add := func(hosts []string, p errorPage) {
		m := obj{"vars": obj{errorStatusPlaceholder: []string{"502", "503", "504"}}}
		if hosts != nil {
			m["host"] = hosts
		}
		out = append(out, obj{"match": []any{m}, "handle": []any{p.handler(errorStatusPlaceholder)}, "terminal": true})
	}
	if len(dashboard) > 0 {
		add(dashboard, pageDashboardError)
	}
	if len(apps) > 0 {
		add(apps, pageAppError)
	}
	add(nil, pageUpstreamError)
	return out
}
