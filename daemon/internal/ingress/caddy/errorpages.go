// Error pages of the edge (docs/05 §4): every answer Caddy gives itself has
// a small HTML page for browsers and a plain body for curl and API clients.
// Pages are self-contained (inline CSS and mark, no scripts, no external
// requests) and only ever contain constant text, the status code and, where
// the request matched a route's validated hosts, {http.request.host}.

// errorPage is one edge answer.
type errorPage struct {
	title, text string // HTML heading and one-line explanation
	plain       string // body for clients that do not accept text/html
	plainType   string // Content-Type of plain; "" = text/plain
	// host shows {http.request.host}. Only for pages served inside a route
	// whose host matcher passed: Caddy does not escape placeholders, and the
	// route hosts are validated hostnames ([a-z0-9.-]), unlike the Host
	// header of an unmatched request.
	host bool
	// refresh reloads the page every 10 s (transient states).
	refresh bool
	// reference shows the firewall's transaction id ({http.error.id}: a
	// random alphanumeric id generated by Coraza, never request data).
	reference bool
}

