// errorStatusPlaceholder is the status of the error in errors routes.
const errorStatusPlaceholder = "{http.error.status_code}"

// handler answers with the page: a subroute serving the HTML page to clients
// that accept text/html and the plain body to everyone else. status is an
// int or errorStatusPlaceholder.
func (p errorPage) handler(status any) obj {
	plainType := p.plainType
	if plainType == "" {
		plainType = "text/plain; charset=utf-8"
	}
	return obj{"handler": "subroute", "routes": []any{
		obj{
			"match":    []any{obj{"header": obj{"Accept": []string{"*text/html*"}}}},
			"handle":   []any{response(status, p.html(fmt.Sprint(status)), "text/html; charset=utf-8")},
			"terminal": true,
		},
		obj{"handle": []any{response(status, p.plain, plainType)}},
	}}
}

func response(status any, body, contentType string) obj {
	return obj{"handler": "static_response", "status_code": status, "body": body, "headers": obj{
		"Content-Type":  []string{contentType},
		"Cache-Control": []string{"no-store"},
	}}
}

