package main

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

// TestSchemasUpToDate fails when protocol/schema/v1 does not match the Go
// types (CI "protocol" gate, docs/10 §6). Fix with `make gen-protocol`.
func TestSchemasUpToDate(t *testing.T) {
	files, err := Generate("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := "../../../protocol/schema/v1"
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(dir, name)) //nolint:gosec // repo path
		if err != nil {
			t.Fatalf("%s: %v (run make gen-protocol)", name, err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is stale; run make gen-protocol", name)
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if _, ok := files[e.Name()]; !ok {
			t.Errorf("%s is not generated by schemagen; remove it or add the type", e.Name())
		}
	}
}

