package mcpclients

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"testing"
)

var update = flag.Bool("update", false, "rewrite protocol/fixtures/cli/mcp-clients.json from Clients")

// fixturePath is the editor table as the dashboard's Settings → AI agents
// page must show it (features/ai-agents/clients.test.ts reads it too).
const fixturePath = "../../../protocol/fixtures/cli/mcp-clients.json"

// SampleDir is the project folder the fixture's NeedsDir entries name, the
// placeholder the dashboard shows.
const sampleDir = "/path/to/your/project"

type fixtureClient struct {
	ID      string            `json:"id"`
	Name    string            `json:"name"`
	Project string            `json:"project"`
	Global  map[string]string `json:"global"`
	Format  string            `json:"format"`
	// Command is the tool's own add command ("" when the CLI's install is used).
	Command  string   `json:"command"`
	NeedsDir bool     `json:"needsDir"`
	Args     []string `json:"args"`
	Snippet  string   `json:"snippet"`
}

func buildFixture() ([]byte, error) {
	out := struct {
		Note    string          `json:"_note"`
		Clients []fixtureClient `json:"clients"`
	}{Note: "Generated by `make gen-cli` from cli/internal/mcpclients; don't edit."}
	for _, c := range Clients {
		args := []string{"mcp"}
		if c.NeedsDir {
			args = append(args, "--dir", sampleDir)
		}
		command := ""
		if c.Command != nil {
			command = c.Command("launchroom", args)
		}
		global := map[string]string{}
		for goos, path := range c.Global {
			global[goos] = filepath.ToSlash(path)
		}
		out.Clients = append(out.Clients, fixtureClient{
			ID: c.ID, Name: c.Name, Project: filepath.ToSlash(c.Project), Global: global, Format: c.Format,
			Command: command, NeedsDir: c.NeedsDir, Args: args, Snippet: c.Snippet("launchroom", args),
		})
	}
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// TestClientsFixture keeps the shared fixture in step with Clients, so the
// dashboard's copy of the table can't drift from `launchroom mcp install`.
func TestClientsFixture(t *testing.T) {
	want, err := buildFixture()
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(fixturePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(have, want) {
		t.Fatalf("%s is stale: run make gen-cli", fixturePath)
	}
}
